/* Apaga os relacionamentos */
ALTER TABLE LABDATABASE.LOCACOES DROP CONSTRAINT CLIENTES_LOCACOES_FK;
ALTER TABLE LABDATABASE.LOCACOES DROP CONSTRAINT CARROS_LOCACOES_FK;

/* Apaga as tabelas */
DROP TABLE LABDATABASE.LOCACOES;
DROP TABLE LABDATABASE.CARROS;
DROP TABLE LABDATABASE.CLIENTES;

/* Apaga as sequences */
DROP SEQUENCE LABDATABASE.LOCACOES_CODIGO_LOCACAO_SEQ;

/*   1. CRIA AS TABELAS */

CREATE TABLE LABDATABASE.CLIENTES (
    CPF VARCHAR2(11) NOT NULL,
    NOME VARCHAR2(255) NOT NULL,
    TELEFONE VARCHAR2(20),
    CONSTRAINT CLIENTES_PK PRIMARY KEY (CPF)
);

CREATE TABLE LABDATABASE.CARROS (
    PLACA VARCHAR2(7) NOT NULL,
    MODELO VARCHAR2(100) NOT NULL,
    MARCA VARCHAR2(100) NOT NULL,
    VALOR_DIARIA NUMBER(10,2) NOT NULL,
    CONSTRAINT CARROS_PK PRIMARY KEY (PLACA)
);

CREATE TABLE LABDATABASE.LOCACOES (
    CODIGO_LOCACAO NUMBER NOT NULL,
    DATA_INICIO_LOCACAO DATE NOT NULL,
    DATA_PREVISAO_LOCACAO DATE NOT NULL,
    DATA_FIM_LOCACAO DATE NOT NULL,
    DIAS NUMBER(5) NOT NULL,
    VALOR_TOTAL NUMBER(10,2) NOT NULL,
    CPF VARCHAR2(11) NOT NULL,
    PLACA VARCHAR2(7) NOT NULL,
    CONSTRAINT LOCACOES_PK PRIMARY KEY (CODIGO_LOCACAO)
);


/*    2. CRIA A SEQUENCE*/

CREATE SEQUENCE LABDATABASE.LOCACOES_CODIGO_LOCACAO_SEQ;


/*    3. CRIA OS RELACIONAMENTOS    */

ALTER TABLE LABDATABASE.LOCACOES
ADD CONSTRAINT CLIENTES_LOCACOES_FK
FOREIGN KEY (CPF)
REFERENCES LABDATABASE.CLIENTES (CPF)
NOT DEFERRABLE;

ALTER TABLE LABDATABASE.LOCACOES
ADD CONSTRAINT CARROS_LOCACOES_FK
FOREIGN KEY (PLACA)
REFERENCES LABDATABASE.CARROS (PLACA)
NOT DEFERRABLE;

/* Garante acesso total as tabelas */
GRANT ALL ON LABDATABASE.CLIENTES TO LABDATABASE;
GRANT ALL ON LABDATABASE.CARROS TO LABDATABASE;
GRANT ALL ON LABDATABASE.LOCACOES TO LABDATABASE;

ALTER USER LABDATABASE quota unlimited on USERS;